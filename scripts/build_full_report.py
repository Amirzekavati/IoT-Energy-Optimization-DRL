def find_browser() -> Path:
    for candidate in (CHROME, EDGE):
        if candidate.exists():
            return candidate
    raise FileNotFoundError("Chrome or Edge not found for PDF export.")


def html_to_pdf(html_path: Path, pdf_path: Path) -> None:
    browser = find_browser()
    USER_DATA.mkdir(parents=True, exist_ok=True)
    tmp = pdf_path.with_suffix(".tmp.pdf")
    if tmp.exists():
        tmp.unlink()
    cmd = [
        str(browser),
        "--headless=new",
        "--disable-gpu",
        "--no-first-run",
        "--no-pdf-header-footer",
        "--allow-file-access-from-files",
        f"--user-data-dir={USER_DATA}",
        "--virtual-time-budget=12000",
        f"--print-to-pdf={tmp.resolve()}",
        html_path.resolve().as_uri(),
    ]
    subprocess.run(cmd, check=True, cwd=str(ROOT), timeout=120)
    tmp.replace(pdf_path)


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    HTML_PATH.write_text(build_html(), encoding="utf-8")
    html_to_pdf(HTML_PATH, PDF_PATH)
    PDF_FA.write_bytes(PDF_PATH.read_bytes())
    print("HTML:", HTML_PATH)
    print("PDF:", PDF_PATH)
    print("PDF_FA_bytes:", PDF_FA.stat().st_size if PDF_FA.exists() else 0)
    print("bytes:", PDF_PATH.stat().st_size)


if __name__ == "__main__":
    try:
        main()
    except subprocess.CalledProcessError as exc:
        print("PDF export failed:", exc, file=sys.stderr)
        sys.exit(exc.returncode)
